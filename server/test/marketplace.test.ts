import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { createApp } from '../src/app.js';
import { MemoryStore } from '../src/db/memory-store.js';
import { hashPassword } from '../src/lib/password.js';

const password = 'TestCustomer24!';
const customer = { name: 'KUJUK QA', phone: '+201111111111', city: 'Cairo', area: 'Nasr City', address: '10 Test Street', country: 'Egypt' };

test('KUJUK: multi-seller COD journey, ownership, idempotency, currency and stock contention', async t => {
  assert(!process.env.FIREBASE_PROJECT_ID, 'Run local tests without Firebase production configuration');
  const cwd = process.cwd();
  const sample = await readFile(new URL('../../web/public/kujuk-emblem.png', import.meta.url));
  const dir = await mkdtemp(join(tmpdir(), 'kujuk-test-'));
  t.after(async () => { process.chdir(cwd); await rm(dir, { recursive: true, force: true }); });
  process.chdir(dir);
  const store = new MemoryStore(hashPassword, join(dir, 'db.json'));
  await store.init();
  const server = createApp(store).listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  async function call(path: string, status: number, options: { token?: string; method?: string; body?: unknown; key?: string } = {}) {
    const { token, method = 'GET', body, key } = options;
    const headers: Record<string,string> = {};
    if (token) headers.Authorization = `Bearer ${token}`;
    if (key) headers['Idempotency-Key'] = key;
    if (body !== undefined && !(body instanceof FormData)) headers['Content-Type'] = 'application/json';
    const r = await fetch(`${base}${path}`, { method, headers, body: body instanceof FormData ? body : body === undefined ? undefined : JSON.stringify(body) });
    const json = await r.json();
    assert.equal(r.status, status, `${method} ${path}: ${JSON.stringify(json)}`);
    return json;
  }
  const register = async (name: string) => (await call('/auth/register', 201, { method: 'POST', body: { name, email: `${name.replaceAll(" ", ".")}@example.test`, password, role: 'admin' } }));
  const buyer = await register('buyerqa');
  assert.equal(buyer.user.role, 'customer');
  const buyerLogin = await call('/auth/login', 200, { method: 'POST', body: { email: 'buyerqa@example.test', password } });
  const otherBuyer = await register('secondbuyer');
  const admins = await call('/auth/login', 200, { method: 'POST', body: { email: 'admin@kujuk.com', password: 'Admin123!' } });
  const admin = admins.token;
  await call('/admin/stats', 403, { token: buyerLogin.token });
  await call('/admin/commission', 403, { token: buyerLogin.token, method: 'PUT', body: { bps: 10000 } });
  await call('/admin/commission', 200, { token: admin, method: 'PUT', body: { bps: 750 } });
  await call('/orders', 401);
  assert((await call('/products?limit=2', 200)).items.length);
  assert((await call('/products/suggest?q=watch', 200)).products.length);

  async function seller(name: string, slug: string, price: number) {
    const { token, user } = await register(name);
    const { profile } = await call('/seller/apply', 201, { token, method: 'POST', body: { shopNameEn: name, shopNameAr: 'متجر اختبار', legalName: 'QA Placeholder', passportNumber: 'TEST1234', passportCountry: 'Egypt', passportExpiry: '2090-01-01' } });
    const fields = { slug, nameEn: slug, nameAr: 'منتج اختبار', price, stock: 2 };
    await call('/seller/products', 403, { token, method: 'POST', body: fields });
    await call(`/admin/sellers/${profile.id}/status`, 409, { token: admin, method: 'PUT', body: { status: 'approved' } });
    const invalid = new FormData(); invalid.set('file', new Blob(['not an image'], { type: 'image/png' }), 'test.png');
    await call('/seller/document', 415, { token, method: 'POST', body: invalid });
    const file = new FormData(); file.set('file', new Blob([new Uint8Array(sample)], { type: 'image/png' }), 'verification-fixture.png');
    const { profile: uploaded } = await call('/seller/document', 201, { token, method: 'POST', body: file });
    assert.equal((await fetch(`${base.replace('/api', '')}/uploads/${uploaded.passportDocument}`)).status, 404);
    await call(`/admin/sellers/${profile.id}/document`, 403, { token });
    assert.equal((await fetch(`${base}/admin/sellers/${profile.id}/document`, { headers: { Authorization: `Bearer ${admin}` } })).status, 200);
    await call(`/admin/sellers/${profile.id}/status`, 200, { token: admin, method: 'PUT', body: { status: 'approved' } });
    const { product } = await call('/seller/products', 201, { token, method: 'POST', body: fields });
    return { token, user, product, profile };
  }
  const a = await seller('Alpha QA Shop', 'qa-alpha-product', 25);
  const b = await seller('Beta QA Shop', 'qa-beta-product', 40);
  const c = await seller('Gamma QA Shop', 'qa-gamma-product', 55);
  assert.deepEqual((await call('/products?q=Beta%20QA%20Shop', 200)).items.map((p: { id: number }) => p.id), [b.product.id]);
  await call(`/seller/products/${b.product.id}`, 404, { token: a.token, method: 'PUT', body: { price: 1 } });
  await call(`/seller/products/${b.product.id}`, 404, { token: a.token, method: 'DELETE' });
  await call('/seller/shop', 200, { token: b.token, method: 'PUT', body: { logo: null, cover: null, descriptionEn: 'About our store', descriptionAr: 'عن متجرنا' } });
  const { shop, items: shopItems } = await call(`/shops/${b.user.id}`, 200);
  assert.equal(shop.descriptionEn, 'About our store');
  assert.equal(shop.passportNumber, undefined);
  assert.deepEqual(shopItems.map((p: { id: number }) => p.id), [b.product.id]);
  await call('/currency', 201, { token: admin, method: 'POST', body: { rate: 4 } });
  const { token } = buyerLogin;
  const items = [{ productId: a.product.id, quantity: 1 }, { productId: b.product.id, quantity: 1 }];
  const quoteInput = { items, country: 'Egypt', currency: 'SDG' };
  const quote = await call('/orders/quote', 200, { token, method: 'POST', body: quoteInput });
  assert.equal(quote.shipments, 2);
  assert.equal(quote.shipping, 47.92);
  assert.equal(quote.total, 307.92);
  await call('/orders/quote', 400, { token, method: 'POST', body: { ...quoteInput, items: [items[0], items[0]] } });
  const body = { items, customer, currency: 'SDG', paymentMethod: 'cod', expectedTotal: quote.total };
  await call('/orders', 400, { token, method: 'POST', key: randomUUID(), body: { ...body, paymentMethod: 'online' } });
  await call('/orders', 409, { token, method: 'POST', key: randomUUID(), body: { ...body, expectedTotal: 1 } });
  const key = randomUUID();
  const { order } = await call('/orders', 201, { token, method: 'POST', key, body });
  assert.equal(order.shipments.length, 2);
  assert.equal(order.checkoutHash, undefined);
  assert.equal((await call(`/orders/recovery/${key}`, 200, { token })).order.id, order.id);
  assert.equal((await call(`/orders/recovery/${key}`, 200, { token: otherBuyer.token })).order, null);
  assert.equal((await call('/orders', 200, { token, method: 'POST', key, body })).order.id, order.id);
  await call('/orders', 409, { token, method: 'POST', key, body: { ...body, customer: { ...customer, address: 'Another address' } } });
  await call(`/orders/${order.id}`, 404, { token: otherBuyer.token });
  const { order: tracking } = await call(`/orders/track/${order.reference}`, 200);
  assert.equal(tracking.customer, undefined);
  assert.equal(tracking.total, undefined);
  for (const seller of [a,b]) {
    const view = (await call('/seller/orders', 200, { token: seller.token })).items[0];
    assert.equal(view.items.length, 1);
    assert.equal(view.items[0].productId, seller.product.id);
    assert.equal(view.userId, undefined);
    assert(!view.reference.includes(order.reference));
    assert.equal(view.checkoutHash, undefined);
    assert.equal(view.commissionBps, 750);
    assert(view.total < order.total);
  }
  await call(`/seller/orders/${order.id}/status`, 404, { token: c.token, method: 'PUT', body: { status: 'processing' } });
  await call(`/seller/orders/${order.id}/status`, 409, { token: a.token, method: 'PUT', body: { status: 'delivered' } });
  for (const status of ['processing','shipped','delivered']) await call(`/seller/orders/${order.id}/status`, 200, { token: a.token, method: 'PUT', body: { status } });
  await call(`/admin/orders/${order.id}/status`, 200, { token: admin, method: 'PUT', body: { status: 'cancelled', sellerId: b.user.id } });
  await call(`/admin/orders/${order.id}/status`, 200, { token: admin, method: 'PUT', body: { status: 'cancelled', sellerId: b.user.id } });
  assert.equal((await store.getProductById(b.product.id))?.stock, 2);
  assert.equal((await call('/seller/stats', 200, { token: a.token })).totalCommission, 1.88);
  await call('/currency', 201, { token: admin, method: 'POST', body: { rate: 5 } });
  const snapshot = (await call(`/orders/${order.id}`, 200, { token })).order;
  assert.equal(snapshot.total, quote.total);
  assert.equal(snapshot.exchangeRate, 4);
  assert.equal(snapshot.amountDue, 123.96);
  assert.equal(snapshot.status, 'delivered');
  await call(`/seller/products/${a.product.id}`, 200, { token: a.token, method: 'DELETE' });
  assert.equal((await call('/seller/orders', 200, { token: a.token })).items[0].items[0].productId, a.product.id);

  const last = [{ productId: c.product.id, quantity: 2 }];
  const lastQuote = await call('/orders/quote', 200, { token, method: 'POST', body: { items: last, country: 'Sudan' } });
  const place = (auth: string) => fetch(`${base}/orders`, { method: 'POST', headers: { Authorization: `Bearer ${auth}`, 'Idempotency-Key': randomUUID(), 'Content-Type': 'application/json' }, body: JSON.stringify({ items: last, customer: { ...customer, country: 'Sudan' }, paymentMethod: 'cod', expectedTotal: lastQuote.total }) });
  const both = await Promise.all([place(token), place(otherBuyer.token)]);
  assert.deepEqual(both.map(r => r.status).sort(), [201,409]);
  assert.equal((await store.getProductById(c.product.id))?.stock, 0);
  await call(`/admin/sellers/${b.profile.id}/status`, 200, { token: admin, method: 'PUT', body: { status: 'suspended' } });
  await call('/seller/orders', 403, { token: b.token });
  await call(`/products/${b.product.slug}`, 404);
});
